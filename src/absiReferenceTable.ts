/** Mean/SD of ABSI for a given age (clamped 18–85) and sex, per Table S1 above. */
export function absiReference(age: number, sex: "male" | "female"): { mean: number; sd: number } {
  const clampedAge = Math.min(85, Math.max(18, Math.round(age)));
  const row = ABSI_REFERENCE_TABLE[clampedAge - 18];
  return sex === "male" ? { mean: row[1], sd: row[2] } : { mean: row[3], sd: row[4] };
}
